def valid_spdx_expression(value: str) -> bool:
    """Validate the supported SPDX identifier, WITH, AND, OR, and parentheses grammar."""
    if not isinstance(value, str) or not value or value != value.strip() or any(character.isspace() and character != " " for character in value):
        return False
    tokens = re.findall(r"\(|\)|[^ ()]+", value)
    if " ".join(tokens).replace("( ", "(").replace(" )", ")") != value:
        return False

    def is_identifier(token: str) -> bool:
        return token not in ('AND', 'OR', 'WITH') and (
            SPDX_IDENTIFIER.fullmatch(token) is not None or SPDX_EXTERNAL_IDENTIFIER.fullmatch(token) is not None
        )

    depth = 0
    expect_primary = True
    can_have_exception = False
    position = 0
    while position < len(tokens):
        token = tokens[position]
        if expect_primary:
            if token == "(":
                depth += 1
                if depth > 128:
                    return False
                can_have_exception = False
            elif is_identifier(token):
                expect_primary = False
                can_have_exception = True
            else:
                return False
        elif token == "WITH":
            position += 1
            if not can_have_exception or position >= len(tokens) or not is_identifier(tokens[position]):
                return False
            can_have_exception = False
        elif token in {"AND", "OR"}:
            expect_primary = True
            can_have_exception = False
        elif token == ")":
            if depth == 0:
                return False
            depth -= 1
            can_have_exception = False
        else:
            return False
        position += 1
    return not expect_primary and depth == 0


def comparable(text: str) -> str:
    """Drop the one line a projection is allowed to rewrite: its provenance pointer."""
    return "\n".join(line for line in text.splitlines() if not line.strip().startswith("canonical-source:"))


def safe_relative(value: str) -> str:
    """Validate a path without touching the filesystem."""
    if not isinstance(value, str) or not value:
        raise ValueError("invalid manifest path")
    posix = PurePosixPath(value.replace("\\", "/"))
    windows = PureWindowsPath(value)
    if posix.is_absolute() or windows.is_absolute() or windows.drive or ".." in posix.parts:
        raise ValueError(f"unsafe manifest path: {value}")
    return posix.as_posix()


def is_indirect(path: Path) -> bool:
    """Detect symlinks and Windows reparse points without following them."""
    if path.is_symlink():
        return True
    try:
        attributes = getattr(os.lstat(path), "st_file_attributes", 0)
    except FileNotFoundError:
        return False
    return bool(attributes & 0x400)


def guarded_path(root: Path, relative: str) -> Path:
    """Reject unsafe or indirect paths before any content read."""
    canonical = root.resolve(strict=True)
    safe = safe_relative(relative)
    current = canonical
    for part in PurePosixPath(safe).parts:
        current /= part
        if current.exists() or current.is_symlink():
            if is_indirect(current):
                raise ValueError(f"indirect manifest path: {relative}")
    if not current.resolve(strict=False).is_relative_to(canonical):
        raise ValueError(f"manifest path escapes repository: {relative}")
    return current


def parse_manifest(raw: bytes, expected_sha256: str) -> dict:
    """Authenticate exact bytes, then validate the checker schema."""
    if hashlib.sha256(raw).hexdigest() != expected_sha256:
        raise ValueError("manifest digest mismatch")
    manifest = json.loads(raw.decode("utf-8"))
    if not isinstance(manifest, dict) or not MANIFEST_FIELDS <= set(manifest) or not set(manifest) - MANIFEST_FIELDS <= OPTIONAL_MANIFEST_FIELDS:
        raise ValueError("unexpected manifest schema")
    if manifest["schemaVersion"] != "3.0":
        raise ValueError("unsupported manifest schema")
    if manifest["generator"] != {"name": "repo-harness-builder", "version": "3.0"}:
        raise ValueError("unexpected manifest generator")
    project = manifest["project"]
    if not isinstance(project, dict) or set(project) != {"id", "ignoreCodegraph", "rulebook"}:
        raise ValueError("unexpected project schema")
    if not isinstance(project["ignoreCodegraph"], bool):
        raise ValueError("unexpected CodeGraph ignore choice")
    safe_relative(project["rulebook"])
    runtimes = manifest["runtimes"]
    if not isinstance(runtimes, list) or len(runtimes) != len(set(runtimes)) or not set(runtimes) <= RUNTIMES:
        raise ValueError("unexpected runtimes")
    if manifest["integrationMode"] not in {"integrated", "standalone"}:
        raise ValueError("unexpected integration mode")
    if manifest["writeSemantics"] != "additive-create-with-bounded-root-append":
        raise ValueError("unexpected write semantics")
    if not valid_spdx_expression(manifest["skillLicense"]):
        raise ValueError("unexpected generated skill license")
    if manifest["localState"] != LOCAL_STATE:
        raise ValueError("unexpected local-state taxonomy")
    for item in manifest["localState"].values():
        safe_relative(item["path"])
    language = manifest["language"]
    if not isinstance(language, dict) or set(language) != {"conversation", "documentation"}:
        raise ValueError("unexpected language schema")
    if language["conversation"] not in REPORT_LANGUAGES:
        raise ValueError("unexpected conversation language")
    documentation = language["documentation"]
    if (
        not isinstance(documentation, list)
        or not documentation
        or len(documentation) != len(set(documentation))
        or not set(documentation) <= DOCUMENTATION_LANGUAGES
        or tuple(documentation) not in (("en",), ("es",), ("en", "es"))
    ):
        raise ValueError("unexpected documentation languages")
    skills = manifest["canonicalSkills"]
    if not isinstance(skills, dict) or not skills:
        raise ValueError("unexpected canonical skills")
    for name, relative in skills.items():
        if not isinstance(name, str) or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise ValueError("invalid canonical skill name")
        safe_relative(relative)
    if "canonicalReferences" in manifest:
        references = manifest["canonicalReferences"]
        expected_references = sorted(
            f".repo-harness/skills/{name}/references/{filename}"
            for name, filenames in {'repo-harness-session-start': ('reconciliation.md', 'checkpoint.md', 'synchronization.md'), 'repo-harness-session-stop': ('checkpoint.md', 'git-commit.md', 'git-transport.md')}.items()
            if name in skills
            for filename in filenames
        )
        if not isinstance(references, list) or references != expected_references:
            raise ValueError("unexpected canonical skill references")
        for relative in references:
            safe_relative(relative)
    commands = manifest["canonicalCommands"]
    if not isinstance(commands, dict) or not commands:
        raise ValueError("unexpected canonical commands")
    for name, families in commands.items():
        if not isinstance(name, str) or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise ValueError("invalid canonical command name")
        if not isinstance(families, dict) or (not families and runtimes) or not set(families) <= {"commands", "prompts"}:
            raise ValueError("unexpected canonical command families")
        for relative in families.values():
            safe_relative(relative)
    projections = manifest.get("canonicalProjections", {})
    if not isinstance(projections, dict):
        raise ValueError("unexpected canonical projections")
    for canonical, targets in projections.items():
        safe_relative(canonical)
        if not isinstance(targets, dict) or set(targets) != set(runtimes):
            raise ValueError("unexpected canonical projection runtimes")
        for runtime, relative in targets.items():
            if runtime not in RUNTIMES:
                raise ValueError("unexpected canonical projection runtime")
            safe_relative(relative)
    return manifest


