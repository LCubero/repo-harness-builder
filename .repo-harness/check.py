#!/usr/bin/env python3
"""Report whether the runtime copies still match the canonical skills. Writes nothing.

Generated by repo-harness-builder; source: core/check-script:3.0
"""

from __future__ import annotations

import json
import hashlib
import os
import re
from pathlib import Path, PurePosixPath, PureWindowsPath

HARNESS = Path(__file__).resolve().parent
MANIFEST_SHA256 = "0a355c943b3657502ff5d61b3fabb696281747ea7b40881764eadd679b0c93ce"
MANIFEST_FIELDS = {"schemaVersion", "generator", "project", "runtimes", "canonicalSkills", "writeSemantics", "integrationMode", "language"}
REPORT_LANGUAGES = {"english", "espanol"}
DOCUMENTATION_LANGUAGES = {"en", "es"}
RUNTIMES = {"claude-code", "opencode", "pi"}
SKILL_SURFACES = {
    "claude-code": ".claude/skills/{name}/SKILL.md",
    "opencode": ".opencode/skills/{name}/SKILL.md",
}


def comparable(text: str) -> str:
    """Drop the one line a projection is allowed to rewrite: its provenance pointer."""
    return "\n".join(line for line in text.splitlines() if not line.strip().startswith("canonical-source:"))


def safe_relative(value: str) -> str:
    """Validate a path without touching the filesystem."""
    if not isinstance(value, str) or not value:
        raise ValueError("invalid manifest path")
    posix = PurePosixPath(value.replace("\\", "/"))
    windows = PureWindowsPath(value)
    if posix.is_absolute() or windows.is_absolute() or windows.drive or ".." in posix.parts:
        raise ValueError(f"unsafe manifest path: {value}")
    return posix.as_posix()


def is_indirect(path: Path) -> bool:
    """Detect symlinks and Windows reparse points without following them."""
    if path.is_symlink():
        return True
    try:
        attributes = getattr(os.lstat(path), "st_file_attributes", 0)
    except FileNotFoundError:
        return False
    return bool(attributes & 0x400)


def guarded_path(root: Path, relative: str) -> Path:
    """Reject unsafe or indirect paths before any content read."""
    canonical = root.resolve(strict=True)
    safe = safe_relative(relative)
    current = canonical
    for part in PurePosixPath(safe).parts:
        current /= part
        if current.exists() or current.is_symlink():
            if is_indirect(current):
                raise ValueError(f"indirect manifest path: {relative}")
    if not current.resolve(strict=False).is_relative_to(canonical):
        raise ValueError(f"manifest path escapes repository: {relative}")
    return current


def parse_manifest(raw: bytes, expected_sha256: str) -> dict:
    """Authenticate exact bytes, then validate the checker schema."""
    if hashlib.sha256(raw).hexdigest() != expected_sha256:
        raise ValueError("manifest digest mismatch")
    manifest = json.loads(raw.decode("utf-8"))
    if not isinstance(manifest, dict) or set(manifest) != MANIFEST_FIELDS:
        raise ValueError("unexpected manifest schema")
    if manifest["schemaVersion"] != "3.0":
        raise ValueError("unsupported manifest schema")
    if manifest["generator"] != {"name": "repo-harness-builder", "version": "3.0"}:
        raise ValueError("unexpected manifest generator")
    project = manifest["project"]
    if not isinstance(project, dict) or set(project) != {"id", "rulebook"}:
        raise ValueError("unexpected project schema")
    safe_relative(project["rulebook"])
    runtimes = manifest["runtimes"]
    if not isinstance(runtimes, list) or len(runtimes) != len(set(runtimes)) or not set(runtimes) <= RUNTIMES:
        raise ValueError("unexpected runtimes")
    if manifest["integrationMode"] not in {"integrated", "standalone"}:
        raise ValueError("unexpected integration mode")
    if manifest["writeSemantics"] != "additive-create-with-runtime-pointer-append":
        raise ValueError("unexpected write semantics")
    language = manifest["language"]
    if not isinstance(language, dict) or set(language) != {"conversation", "documentation"}:
        raise ValueError("unexpected language schema")
    if language["conversation"] not in REPORT_LANGUAGES:
        raise ValueError("unexpected conversation language")
    documentation = language["documentation"]
    if (
        not isinstance(documentation, list)
        or not documentation
        or len(documentation) != len(set(documentation))
        or not set(documentation) <= DOCUMENTATION_LANGUAGES
        or documentation[0] != "en"
    ):
        raise ValueError("unexpected documentation languages")
    skills = manifest["canonicalSkills"]
    if not isinstance(skills, dict) or not skills:
        raise ValueError("unexpected canonical skills")
    for name, relative in skills.items():
        if not isinstance(name, str) or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise ValueError("invalid canonical skill name")
        safe_relative(relative)
    return manifest


def check_projections(root: Path) -> dict:
    """Compare every canonical skill against its runtime copies without writing."""
    manifest_path = guarded_path(root, ".repo-harness/manifest.json")
    manifest = parse_manifest(manifest_path.read_bytes(), MANIFEST_SHA256)
    entries = []
    for name, canonical_relative in sorted(manifest["canonicalSkills"].items()):
        canonical = guarded_path(root, canonical_relative)
        if not canonical.is_file():
            entries.append({"skill": name, "path": canonical_relative, "state": "canonical-missing"})
            continue
        expected = comparable(canonical.read_bytes().decode("utf-8"))
        for runtime in manifest["runtimes"]:
            surface = SKILL_SURFACES.get(runtime)
            if surface is None:
                continue
            relative = surface.format(name=name)
            target = guarded_path(root, relative)
            if not target.is_file():
                state = "missing"
            elif comparable(target.read_bytes().decode("utf-8")) != expected:
                state = "stale"
            else:
                state = "current"
            entries.append({"skill": name, "runtime": runtime, "path": relative, "state": state})
    drifted = [entry for entry in entries if entry["state"] != "current"]
    return {"status": "drift" if drifted else "current", "files": entries, "writes": 0}


def main() -> int:
    """Print the report and exit non-zero when a copy is stale or missing."""
    report = check_projections(HARNESS.parent)
    print(json.dumps(report, indent=2, sort_keys=True))
    return 1 if report["status"] == "drift" else 0


if __name__ == "__main__":
    raise SystemExit(main())
