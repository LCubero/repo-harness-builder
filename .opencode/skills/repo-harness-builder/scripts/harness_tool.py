def check_staged_scope(
    approved: tuple[tuple[str, str], ...],
    pre_existing: tuple[tuple[str, str], ...],
    staged: tuple[tuple[str, str], ...],
) -> dict[str, Any]:
    """Compare workflow-staged paths and status/modes with the approved scope."""
    approved_by_path = dict(approved)
    pre_existing_by_path = dict(pre_existing)
    staged_by_path = dict(staged)
    workflow_staged = {path: state for path, state in staged if path not in pre_existing_by_path}
    extra = tuple(sorted((path, state) for path, state in workflow_staged.items() if path not in approved_by_path))
    missing = tuple(sorted((path, state) for path, state in approved_by_path.items() if path not in workflow_staged))
    changed = tuple(
        sorted(
            (path, approved_state, workflow_staged[path])
            for path, approved_state in approved_by_path.items()
            if path in workflow_staged and workflow_staged[path] != approved_state
        )
    )
    pre_existing_changed = tuple(
        sorted(
            (path, state, staged_by_path.get(path, "missing"))
            for path, state in pre_existing_by_path.items()
            if staged_by_path.get(path) != state
        )
    )
    return {
        "outcome": "pause" if extra or missing or changed or pre_existing_changed else "continue",
        "extra": extra,
        "missing": missing,
        "changed": changed,
        "pre_existing_changed": pre_existing_changed,
    }


def dump_json(value: Any) -> str:
    """Return deterministic, ASCII-safe JSON."""
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def load_json(path: Path) -> Any:
    """Load one UTF-8 JSON file."""
    return json.loads(path.read_text(encoding="utf-8"))


def digest_bytes(value: bytes) -> str:
    """Return a SHA-256 digest for bytes."""
    return hashlib.sha256(value).hexdigest()


def digest_text(value: str) -> str:
    """Return a SHA-256 digest for UTF-8 text."""
    return digest_bytes(value.encode("utf-8"))


def pointer_addition(current: bytes, directive: str) -> bytes:
    """Return the smallest newline-delimited bytes needed for one pointer."""
    newline = b"\r\n" if b"\r\n" in current and b"\n" not in current.replace(b"\r\n", b"") else b"\n"
    separator = b"" if not current or current.endswith((b"\n", b"\r")) else newline
    return separator + directive.encode("utf-8") + newline


def has_pointer_line(current: bytes, directive: str) -> bool:
    """Match the required ASCII directive as one exact line with any line ending."""
    return directive.encode("utf-8") in current.splitlines()


def has_codegraph_ignore_line(current: bytes) -> bool:
    """Match either accepted root CodeGraph ignore directive as one exact line."""
    return any(has_pointer_line(current, directive) for directive in (CODEGRAPH_IGNORE_DIRECTIVE, "/.codegraph/"))


def has_local_state_ignore_line(current: bytes, directive: str) -> bool:
    """Match either equivalent root form of one local-state ignore directive."""
    return any(has_pointer_line(current, candidate) for candidate in (directive, directive.removeprefix("/")))


def missing_gitignore_directives(current: bytes, ignore_codegraph: bool) -> tuple[str, ...]:
    """Return exact rendered root directives that are not already represented."""
    missing = [
        directive
        for directive in LOCAL_STATE_IGNORE_DIRECTIVES
        if not has_local_state_ignore_line(current, directive)
    ]
    if ignore_codegraph and not has_codegraph_ignore_line(current):
        missing.insert(0, CODEGRAPH_IGNORE_DIRECTIVE)
    return tuple(missing)


def byte_compared_paths(outputs: Mapping[str, str], rulebook_path: str) -> tuple[str, ...]:
    """Return generated paths whose exact bytes checking compares.

    Pointer, ignore, and attribute files carry directives rather than exact
    bytes, and human-owned documents are checked structurally, so none of them
    depend on preserved LF checkout bytes.
    """
    excluded = {*POINTER_DIRECTIVES, GITIGNORE_PATH, GITATTRIBUTES_PATH}
    return tuple(
        path for path in sorted(outputs) if path not in excluded and not human_owned(path, rulebook_path)
    )


def git_attribute_rules(outputs: Mapping[str, str], rulebook_path: str) -> tuple[str, ...]:
    """Return the exact LF rules protecting every byte-compared generated path."""
    return tuple(f"{path} text eol=lf" for path in byte_compared_paths(outputs, rulebook_path))


def missing_attribute_rules(current: bytes, rules: Sequence[str]) -> tuple[str, ...]:
    """Return only exact required rules absent from a human-owned attributes file."""
    return tuple(rule for rule in rules if not has_pointer_line(current, rule))


def attribute_pattern_matches(pattern: str, path: str) -> bool:
    """Evaluate the bounded root attribute patterns against repository-relative paths."""
    if not pattern or pattern.startswith(("#", "!", "[attr]")) or pattern.endswith("/"):
        return False
    normalized = pattern.removeprefix("/")
    if normalized.endswith("/**"):
        return path.startswith(normalized.removesuffix("**"))
    return PurePosixPath(path).match(normalized)


def conflicting_attribute_paths(current: bytes, protected: Sequence[str]) -> set[str]:
    """Return protected paths touched by a text or eol assignment incompatible with LF."""
    conflicts: set[str] = set()
    lines = current.decode("utf-8", errors="replace").splitlines()
    macros = {
        fields[0].removeprefix("[attr]"): fields[1:]
        for raw_line in lines
        if len(fields := raw_line.split()) >= 2 and fields[0].startswith("[attr]")
    }

    def expand(assignments: list[str], seen: set[str] | None = None) -> list[str]:
        expanded: list[str] = []
        visited = set() if seen is None else seen
        for assignment in assignments:
            if assignment in macros and assignment not in visited:
                expanded.extend(expand(macros[assignment], visited | {assignment}))
            else:
                expanded.append(assignment)
        return expanded

    for raw_line in lines:
        fields = raw_line.split()
        if len(fields) < 2:
            continue
        pattern, assignments = fields[0], expand(fields[1:])
        lf_pinned = "eol=lf" in assignments
        incompatible = any(
            assignment == "binary"
            or assignment == "eol"
            or assignment.startswith(("-text", "!text", "-eol", "!eol"))
            or (assignment.startswith("text=") and not (assignment == "text=auto" and lf_pinned))
            or (assignment.startswith("eol=") and assignment != "eol=lf")
            for assignment in assignments
        )
        if not incompatible:
            continue
        conflicts.update(path for path in protected if attribute_pattern_matches(pattern, path))
    return conflicts


def pointer_additions(current: bytes, directives: Sequence[str]) -> bytes:
    """Return exact newline-preserving append bytes for an ordered directive set."""
    addition = b""
    for directive in directives:
        addition += pointer_addition(current + addition, directive)
    return addition


def generated_version(current: bytes, replacement_evidence: Optional[str] = None) -> Optional[str]:
    """Return proven repo-harness-builder provenance from generated bytes."""
    text = current.decode("utf-8", errors="replace")
    if GENERATED_MARKER not in text:
        return replacement_evidence
    match = re.search(r"version:\s*[\"']?(\d+\.\d+)", text)
    if not match:
        match = re.search(r"source: [^\n:]+:(\d+\.\d+)", text)
    return match.group(1) if match else "legacy"


def safe_relative(value: str) -> str:
    """Normalize and validate one repository-relative path."""
    path = PurePosixPath(value.replace("\\", "/"))
    require(bool(value) and not path.is_absolute() and ".." not in path.parts, f"unsafe relative path: {value}")
    require(not re.match(r"^[A-Za-z]:", value), f"unsafe relative path: {value}")
    return str(path)


def is_indirect(path: Path) -> bool:
    """Detect symlinks and Windows reparse points without following them."""
    if path.is_symlink():
        return True
    try:
        attributes = getattr(path.stat(follow_symlinks=False), "st_file_attributes", 0)
    except FileNotFoundError:
        return False
    return bool(attributes & 0x400)


def guarded_target(root: Path, relative: str) -> Path:
    """Return a contained target after rejecting indirect existing ancestors."""
    canonical = root.resolve(strict=True)
    require(canonical.is_dir() and not is_indirect(canonical), "root must be a direct directory")
    target = canonical / safe_relative(relative)
    current = canonical
    for part in PurePosixPath(safe_relative(relative)).parts[:-1]:
        current /= part
        if current.exists() or current.is_symlink():
            require(not is_indirect(current), f"indirect output ancestor: {relative}")
