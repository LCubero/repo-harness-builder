def authentic_installed_checker(checker_bytes: bytes, manifest_bytes: bytes) -> bool:
    """Prove the installed checker authenticates these exact manifest bytes.

    Byte equality with the current template proves freshness, not authenticity.
    Gating on freshness made a stale checker disable its own replacement and
    every other manifest-owned output with it, so an installation could never
    receive a corrected checker. Authenticity is builder provenance plus the
    embedded digest naming these manifest bytes, which is exactly what the
    manifest authentication depends on.
    """
    if generated_version(checker_bytes) is None:
        return False
    match = re.search(r'MANIFEST_SHA256\s*=\s*"([0-9a-f]{64})"', checker_bytes.decode("utf-8", errors="replace"))
    return bool(match) and match.group(1) == digest_bytes(manifest_bytes)


def declared_skill_license(root: Path) -> Optional[str]:
    """Read a selected license only from an authenticated installed manifest.

    Historical manifests predate this field, so their selected license remains
    unknown. Unauthenticated manifest bytes never select generated output.
    """
    manifest_target = guarded_target(root, MANIFEST_PATH)
    checker_target = guarded_target(root, ".repo-harness/check.py")
    if not manifest_target.is_file() or is_indirect(manifest_target):
        return GENERATED_SKILL_LICENSE
    if not checker_target.is_file() or is_indirect(checker_target):
        return GENERATED_SKILL_LICENSE
    manifest_bytes = manifest_target.read_bytes()
    if not authentic_installed_checker(checker_target.read_bytes(), manifest_bytes):
        return GENERATED_SKILL_LICENSE
    manifest = json.loads(manifest_bytes)
    return validated_manifest_skill_license(manifest, allow_historical=True)


def manifest_owned_generated_paths(root: Path) -> set[str]:
    """Return generated paths authorized by an authenticated installed manifest."""
    manifest_target = guarded_target(root, MANIFEST_PATH)
    checker_target = guarded_target(root, ".repo-harness/check.py")
    if not manifest_target.is_file() or is_indirect(manifest_target):
        return set()
    if not checker_target.is_file() or is_indirect(checker_target):
        return set()
    manifest_bytes = manifest_target.read_bytes()
    checker_bytes = checker_target.read_bytes()
    if checker_bytes.decode("utf-8", errors="replace") != check_script(digest_bytes(manifest_bytes)):
        # Byte equality with the current template proves freshness, not authenticity,
        # and it cannot hold across versions by definition: the checker embeds the
        # version that wrote it. Narrowing to the checker alone here made a version
        # bump freeze every installation, and replacing the checker without its
        # manifest is worse than freezing, because the checker then names manifest
        # bytes nobody wrote and dies with a digest mismatch. Authenticity is builder
        # provenance plus the embedded digest naming these exact manifest bytes, which
        # is what lets the manifest name its own outputs. Every replacement still
        # requires builder provenance on the file being replaced, so a human-owned
        # path stays unreachable from here.
        if not authentic_installed_checker(checker_bytes, manifest_bytes):
            return set()
    try:
        manifest = json.loads(manifest_bytes)
        validated_manifest_skill_license(manifest, allow_historical=True)
        paths = generated_skill_paths(manifest)
    except (ContractError, json.JSONDecodeError):
        return set()
    for runtime in manifest["runtimes"]:
        if runtime == "pi":
            paths.update(f".pi/prompts/{command}.md" for command in COMMAND_TO_SKILL)
            paths.add(".pi/prompts/repo-harness-help.md")
            continue
        base = ".opencode" if runtime == "opencode" else ".claude"
        paths.update(f"{base}/commands/{command}.md" for command in COMMAND_TO_SKILL)
        paths.add(f"{base}/commands/repo-harness-help.md")
    return paths | {MANIFEST_PATH, ".repo-harness/check.py"}


def authenticated_wrapper_versions(root: Path) -> dict[str, str]:
    """Return versions for exact marker-free wrappers owned by an authenticated manifest."""
