def canonical_json(value: Any) -> str:
    """Return exact compact ASCII-safe JSON without a trailing newline."""
    try:
        return json.dumps(
            value,
            ensure_ascii=True,
            allow_nan=False,
            sort_keys=True,
            separators=(",", ":"),
        )
    except (TypeError, ValueError) as error:
        raise ContractError("authority content is not canonicalizable") from error


def _reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ContractError("authority JSON contains duplicate keys")
        result[key] = value
    return result


def _reject_non_finite(_value: str) -> None:
    raise ContractError("authority JSON contains a non-finite value")


def _parse_strict_json(raw: str) -> Any:
    try:
        return json.loads(
            raw,
            object_pairs_hook=_reject_duplicate_keys,
            parse_constant=_reject_non_finite,
        )
    except ContractError:
        raise
    except (json.JSONDecodeError, TypeError) as error:
        raise ContractError("authority JSON is invalid") from error


def _exact_object(value: Any, fields: set[str]) -> dict[str, Any]:
    require(isinstance(value, dict) and set(value) == fields, "authority context schema mismatch")
    return value


def _non_empty_string(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def _string_list(value: Any) -> bool:
    return isinstance(value, list) and all(isinstance(item, str) for item in value)


def _validate_authority_context_schema(value: Any) -> AuthorityContext:
    context = _exact_object(value, CONTEXT_FIELDS)
    require(type(context["schemaVersion"]) is int and context["schemaVersion"] == 1, "authority context schema mismatch")
    require(_non_empty_string(context["materialRevision"]), "authority context schema mismatch")

    project = _exact_object(context["project"], PROJECT_FIELDS)
    require(_non_empty_string(project["id"]) and _non_empty_string(project["name"]), "authority context schema mismatch")

    builder = _exact_object(context["builder"], BUILDER_FIELDS)
    require(_string_list(builder["runtimes"]), "authority context schema mismatch")
    require(_non_empty_string(builder["license"]), "authority context schema mismatch")
    require(
        isinstance(builder["integrationMode"], str)
        and builder["integrationMode"] in {"integrated", "standalone"},
        "authority context schema mismatch",
    )
    require(_non_empty_string(builder["reportLanguage"]), "authority context schema mismatch")
    require(_string_list(builder["documentationLanguages"]), "authority context schema mismatch")
    require(_non_empty_string(builder["conversationLanguage"]), "authority context schema mismatch")
    require(type(builder["ignoreCodegraph"]) is bool, "authority context schema mismatch")
    require(builder["activation"] == "builder", "authority context schema mismatch")
    capabilities = _exact_object(builder["effectiveCapabilities"], {"gentleAi", "engram"})
    for state in capabilities.values():
        require(
            state in {"available", "unavailable", "partial", "disabled", "policy-required"},
            "authority context schema mismatch",
        )

    premises = context["premises"]
    decisions = context["decisions"]
    evidence = context["evidence"]
    require(isinstance(premises, list) and isinstance(decisions, list) and isinstance(evidence, list), "authority context schema mismatch")

    all_ids: set[str] = set()
    decision_ids: set[str] = set()
    evidence_ids: set[str] = set()

    for decision_value in decisions:
        decision = _exact_object(decision_value, DECISION_FIELDS)
        require(_non_empty_string(decision["id"]), "authority context schema mismatch")
        require(decision["kind"] == "human_decision", "authority context schema mismatch")
        require(_non_empty_string(decision["statement"]), "authority context schema mismatch")
        require(decision["id"] not in all_ids, "authority context IDs must be unique")
        all_ids.add(decision["id"])
        decision_ids.add(decision["id"])

    for evidence_value in evidence:
        require(isinstance(evidence_value, dict), "authority context schema mismatch")
        kind = evidence_value.get("kind")
        if kind == "repository_file":
            item = _exact_object(evidence_value, REPOSITORY_FILE_EVIDENCE_FIELDS)
            require(_non_empty_string(item["locator"]), "authority context schema mismatch")
        elif kind == "host_json":
            item = _exact_object(evidence_value, HOST_JSON_EVIDENCE_FIELDS)
            require(item["source"] == "engram_evidence_json", "authority context schema mismatch")
        else:
            raise ContractError("authority context evidence kind is unsupported")
        require(_non_empty_string(item["id"]), "authority context schema mismatch")
        require(isinstance(item["sha256"], str) and SHA256_PATTERN.fullmatch(item["sha256"]) is not None, "authority context schema mismatch")
        require(item["id"] not in all_ids, "authority context IDs must be unique")
        all_ids.add(item["id"])
        evidence_ids.add(item["id"])

    for premise_value in premises:
        premise = _exact_object(premise_value, PREMISE_FIELDS)
        require(_non_empty_string(premise["id"]) and _non_empty_string(premise["value"]), "authority context schema mismatch")
        require(
            isinstance(premise["class"], str)
            and premise["class"] in {"factual_claim", "assistant_interpretation"},
            "authority context schema mismatch",
        )
        require(_string_list(premise["decisionIds"]) and _string_list(premise["evidenceIds"]), "authority context schema mismatch")
        require(len(premise["decisionIds"]) == len(set(premise["decisionIds"])), "authority context references must be unique")
        require(len(premise["evidenceIds"]) == len(set(premise["evidenceIds"])), "authority context references must be unique")
        require(premise["id"] not in all_ids, "authority context IDs must be unique")
        all_ids.add(premise["id"])
        require(set(premise["decisionIds"]).issubset(decision_ids), "authority context has a dangling decision reference")
        require(set(premise["evidenceIds"]).issubset(evidence_ids), "authority context has a dangling evidence reference")

    return context  # type: ignore[return-value]


def parse_authority_context(raw: str) -> tuple[AuthorityContext, str]:
    """Parse one exact canonical authority context transport."""
    require(isinstance(raw, str) and "\n" not in raw and "\r" not in raw, "authority context bytes are not canonical")
    parsed = _validate_authority_context_schema(_parse_strict_json(raw))
    canonical = canonical_json(parsed)
    require(raw == canonical, "authority context bytes are not canonical")
    return parsed, canonical


def validate_authority_context(
    root: Path,
    context: AuthorityContext,
    project_id: str,
    project_name: str,
    expected_config: AuthorityBuilderConfig,
    host_json_inputs: dict[str, str],
) -> list[EvidenceBinding]:
    """Validate typed evidence bindings and return safe metadata only."""
    validated = _validate_authority_context_schema(context)
    require(
        validated["project"]["id"] == project_id
        and validated["project"]["name"] == project_name,
        "authority context project mismatch",
    )
    require(validated["builder"] == expected_config, "authority context configuration mismatch")

    bindings: list[EvidenceBinding] = []
    for item in validated["evidence"]:
        if item["kind"] == "repository_file":
            # The digest was recorded when the answer was believed. The file is re-read and
            # compared, never trusted, because a correction that changed the file must not
            # leave the old plan authorized by evidence that no longer says what it said.
            # Digest shape is already settled by the schema pass through SHA256_PATTERN;
            # re-checking it here would be a branch no input can reach.
            locator = safe_relative(item["locator"])
            target = guarded_target(root, locator)
            require(
                target.is_file() and not is_indirect(target),
                "authority context repository evidence is unavailable",
            )
            actual_bytes_sha256 = hashlib.sha256(target.read_bytes()).hexdigest()
            require(
                actual_bytes_sha256 == item["sha256"],
                "authority context repository evidence changed",
            )
            # Repository-relative locator only. The resolved path and the bytes stay here.
            bindings.append(
                {
                    "id": item["id"],
                    "kind": "repository_file",
                    "locator": locator,
                    "sha256": item["sha256"],
                }
            )
            continue
        source = item["source"]
        require(source == "engram_evidence_json", "authority context host source is unsupported")
        require(source in host_json_inputs, "authority context host input is unavailable")
        parsed_host_json = _parse_strict_json(host_json_inputs[source])
        actual_sha256 = hashlib.sha256(canonical_json(parsed_host_json).encode("utf-8")).hexdigest()
        require(actual_sha256 == item["sha256"], "authority context host input changed")
        bindings.append(
            {
                "id": item["id"],
                "kind": "host_json",
                "source": source,
                "sha256": item["sha256"],
            }
        )
    return bindings


def expected_authority_builder_config(args: argparse.Namespace) -> AuthorityBuilderConfig:
    """Project the exact builder configuration this invocation would run.

    The context declares what the builder is doing; this is the only thing it can be
    compared against. Deriving it here rather than trusting the context is the whole
    point: a context that describes a different build must not authorize this one.

    Runtime and documentation-language order follow what the renderer normalizes, not
    what the caller typed, because the plan is rendered from the normalized order and a
    context bound to the typed order would disagree with the plan it claims to justify.
    """
    effective_capabilities = getattr(args, "effective_capabilities", None)
    if effective_capabilities is None:
        effective_capabilities = (
            {"gentleAi": "disabled", "engram": "disabled"}
            if args.standalone
            else {"gentleAi": "available", "engram": "available"}
        )
    return {
        "runtimes": sorted(set(args.runtime or [])),
        "license": args.license_id or GENERATED_SKILL_LICENSE,
        "integrationMode": "standalone" if args.standalone else "integrated",
        "reportLanguage": args.report_language,
        "documentationLanguages": list(normalize_documentation_languages(args.documentation_languages)),
        "conversationLanguage": args.conversation_language or DEFAULT_REPORT_LANGUAGE,
        "ignoreCodegraph": args.ignore_codegraph,
        "activation": args.activation,
        "effectiveCapabilities": effective_capabilities,
    }


def target_binding_sha256(root: Path) -> str:
    """Hash the normalized destination so identity survives without disclosing the path.

    The normalized path is hashed and discarded. No caller returns or logs it, which is
    what lets a preview name the target it is bound to without naming where it lives.
    """
    resolved = root.resolve(strict=True)
    normalized = os.path.normcase(os.path.normpath(str(resolved)))
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def authority_binding(
    root: Path,
    context: AuthorityContext,
    canonical_context: str,
    evidence: list[EvidenceBinding],
    plan_sha256: str,
) -> AuthorityBinding:
    """Bind one generation to its context, its target, and its plan.

    Three identities have to move together or the binding proves nothing. The context
    says what was believed, the target says which repository it was believed about, and
    the plan says what would be written. Changing any one of them is a different
    generation, which is why an approval cannot survive a correction.
    """
    require(
        isinstance(plan_sha256, str) and re.fullmatch(r"[0-9a-f]{64}", plan_sha256) is not None,
        "authority binding requires a lowercase 64-character plan digest",
    )
    authority_context_sha256 = digest_text(canonical_context)
    target_sha256 = target_binding_sha256(root)
    generation = {
        "domain": "repo-harness-builder/authority-generation/v1",
        "authorityContextSha256": authority_context_sha256,
        "materialRevision": context["materialRevision"],
        "planIdentity": {"schemaVersion": 1, "planSha256": plan_sha256},
        "targetBindingSha256": target_sha256,
    }
    return {
        "evidence": evidence,
        "authorityContextSha256": authority_context_sha256,
        "targetBindingSha256": target_sha256,
        "generationSha256": digest_text(canonical_json(generation)),
    }


def read_authority_context_transport(locator: str) -> str:
    """Read the exact authority context bytes the human explicitly supplied.

    This is a transport the caller named, not an evidence locator: it is read as given
    rather than resolved against the target, which is why a path must be a direct regular
    file and never a symlink into something else.
    """
    if locator == "-":
        return sys.stdin.read()
    path = Path(locator)
    require(path.is_file() and not is_indirect(path), "authority context transport is unavailable")
    return path.read_text(encoding="utf-8")


def builder_authority_projection(root: Path, args: argparse.Namespace, plan_sha256: str) -> dict[str, Any]:
    """Return only what a human can review, and nothing a preview must not disclose.

    Every premise value and decision statement is replaced by an explicit redaction marker
    rather than omitted, because a reader has to see that something was withheld. Evidence
    keeps its stable id, kind, safe locator or source, and content digest, which is enough
    to check what the answer rested on without reproducing it.
    """
    raw = read_authority_context_transport(args.authority_context_file)
    context, canonical_context = parse_authority_context(raw)
    host_json_inputs = (
        {"engram_evidence_json": args.engram_evidence_json} if args.engram_evidence_json else {}
    )
    evidence = validate_authority_context(
        root,
        context,
        args.project_id,
        args.project_name,
        expected_authority_builder_config(args),
        host_json_inputs,
    )
    binding = authority_binding(root, context, canonical_context, evidence, plan_sha256)
    return {
        "authorityEvidence": binding["evidence"],
        "authorityPremises": [
            {"id": premise["id"], "class": premise["class"], "value": REDACTED_MARKER}
            for premise in context["premises"]
        ],
        "authorityDecisions": [
            {"id": decision["id"], "kind": decision["kind"], "statement": REDACTED_MARKER}
            for decision in context["decisions"]
        ],
        "authorityContextSha256": binding["authorityContextSha256"],
        "targetBindingSha256": binding["targetBindingSha256"],
        "generationSha256": binding["generationSha256"],
    }


