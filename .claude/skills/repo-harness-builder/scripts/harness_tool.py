class ContractError(ValueError):
    """Represent a safe, expected contract refusal."""


def require(condition: bool, message: str) -> None:
    """Raise a contract error when a required condition is false."""
    if not condition:
        raise ContractError(message)


def approval_granted(answer: str) -> bool:
    """Accept only the two exact case-sensitive approval answers."""
    require(answer in ("APROBAR", "DENEGAR"), INVALID_APPROVAL)
    return answer == "APROBAR"


def dump_json(value: Any) -> str:
    """Return deterministic, ASCII-safe JSON."""
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def load_json(path: Path) -> Any:
    """Load one UTF-8 JSON file."""
    return json.loads(path.read_text(encoding="utf-8"))


def digest_bytes(value: bytes) -> str:
    """Return a SHA-256 digest for bytes."""
    return hashlib.sha256(value).hexdigest()


def digest_text(value: str) -> str:
    """Return a SHA-256 digest for UTF-8 text."""
    return digest_bytes(value.encode("utf-8"))


def pointer_addition(current: bytes, directive: str) -> bytes:
    """Return the smallest newline-delimited bytes needed for one pointer."""
    separator = b"" if not current or current.endswith((b"\n", b"\r")) else b"\n"
    return separator + directive.encode("utf-8") + b"\n"


def has_pointer_line(current: bytes, directive: str) -> bool:
    """Match the required ASCII directive as one exact line with any line ending."""
    return directive.encode("utf-8") in current.splitlines()


def safe_relative(value: str) -> str:
    """Normalize and validate one repository-relative path."""
    path = PurePosixPath(value.replace("\\", "/"))
    require(bool(value) and not path.is_absolute() and ".." not in path.parts, f"unsafe relative path: {value}")
    require(not re.match(r"^[A-Za-z]:", value), f"unsafe relative path: {value}")
    return str(path)


def is_indirect(path: Path) -> bool:
    """Detect symlinks and Windows reparse points without following them."""
    if path.is_symlink():
        return True
    try:
        attributes = getattr(path.stat(follow_symlinks=False), "st_file_attributes", 0)
    except FileNotFoundError:
        return False
    return bool(attributes & 0x400)


def guarded_target(root: Path, relative: str) -> Path:
    """Return a contained target after rejecting indirect existing ancestors."""
    canonical = root.resolve(strict=True)
    require(canonical.is_dir() and not is_indirect(canonical), "root must be a direct directory")
    target = canonical / safe_relative(relative)
    current = canonical
    for part in PurePosixPath(safe_relative(relative)).parts[:-1]:
        current /= part
        if current.exists() or current.is_symlink():
            require(not is_indirect(current), f"indirect output ancestor: {relative}")
    require(target.resolve(strict=False).is_relative_to(canonical), f"output escapes root: {relative}")
    return target


def normalize_project_name(value: str) -> str:
    """Create a safe lowercase project identifier and filename stem."""
    normalized = re.sub(r"[^a-z0-9]+", "-", value.strip().lower()).strip("-")
    require(bool(normalized), "project name must contain a letter or number")
    return normalized[:80].rstrip("-")


def token_proxy(text: str) -> int:
    """Estimate tokens the way the rulebook budget is meant to be measured.

    Whitespace-delimited words times 1.33. Deliberately crude and deliberately
    mechanical: the point is that nobody judges the budget by eye.
    """
    return round(len(text.split()) * 1.33)


def structural_headings(text: str) -> list[str]:
    """List the level-two headings that define a document's shape, ignoring dated entries."""
    found = [line[3:].strip() for line in text.splitlines() if line.startswith("## ")]
    return [heading for heading in found if not DATE_HEADING.match(heading)]


def frontmatter(name: str, description: str, source: str, license_id: str) -> str:
    """Build generated skill frontmatter with provenance and complete metadata."""
    require(bool(SPDX_EXPRESSION.fullmatch(license_id)), "license must be a single-line SPDX expression")
    return (
        "---\n"
        f"name: {name}\n"
        f'description: "{description}"\n'
        f"license: {json.dumps(license_id)}\n"
        "metadata:\n"
        "  author: repo-harness-builder\n"
        f'  version: "{VERSION}"\n'
        f"  canonical-source: {source}\n"
        "---\n\n"
    )


